const express = require('express');
const dashboardController = require('../controllers/dashboardController');
const clientController = require('../controllers/clientController');
const projectController = require('../controllers/projectController');
const taskController = require('../controllers/taskController');
const financeController = require('../controllers/financeController');
const materialsController = require('../controllers/materialsController');
const suppliersController = require('../controllers/suppliersController');
const scheduleController = require('../controllers/scheduleController');
const mapController = require('../controllers/mapController');
const concreteController = require('../controllers/concreteController');
const authController = require('../controllers/authController');
const companyController = require('../controllers/companyController');
const companyUserController = require('../controllers/companyUserController');
const { requireAuth, requireCompany, requireRole, requireScreen, auditMutations } = require('../middleware/auth');
const { plantUpload } = require('../middleware/plantUpload');

const router = express.Router();

router.post('/login', authController.login);
router.use(requireAuth, auditMutations);
router.get('/me', authController.me);
router.put('/account/password', authController.changePassword);
router.get('/admin/companies', requireRole('super_admin'), companyController.getAll);
router.post('/admin/companies', requireRole('super_admin'), companyController.create);
router.put('/admin/companies/:id', requireRole('super_admin'), companyController.update);
router.post('/admin/companies/:id/admin', requireRole('super_admin'), companyController.createCompanyAdmin);
router.use(requireCompany);
router.get('/admin/users', requireRole('admin'), companyUserController.getAll);
router.post('/admin/users', requireRole('admin'), companyUserController.create);
router.put('/admin/users/:id', requireRole('admin'), companyUserController.update);

router.get('/dashboard', requireScreen('dashboard'), dashboardController.getSummary);
router.get('/clients', requireScreen('clients'), clientController.getAll);
router.post('/clients', requireScreen('clients'), clientController.create);
router.get('/projects', requireScreen('projects'), projectController.getAll);
router.get('/projects/:id/activities', requireScreen('projects'), projectController.getActivities);
router.post('/projects', requireScreen('projects'), requireRole('admin'), projectController.create);
router.put('/projects/:id', requireScreen('projects'), requireRole('admin'), projectController.update);
router.get('/tasks', requireScreen('tasks'), taskController.getAll);
router.post('/tasks', requireScreen('tasks'), taskController.create);
router.get('/finance', requireScreen('finance'), financeController.getAll);
router.post('/finance', requireScreen('finance'), requireRole('admin'), financeController.create);
router.get('/materials', requireScreen('materials'), materialsController.getAll);
router.post('/materials', requireScreen('materials'), requireRole('admin'), materialsController.create);
router.get('/suppliers', requireScreen('suppliers'), suppliersController.getAll);
router.post('/suppliers', requireScreen('suppliers'), requireRole('admin'), suppliersController.create);
router.get('/schedule', requireScreen('schedule'), scheduleController.getAll);
router.post('/schedule', requireScreen('schedule'), requireRole('admin'), scheduleController.create);
router.get('/maps', requireScreen('maps'), mapController.getAll);
router.get('/subdivisions', requireScreen('maps', 'subdivisions'), mapController.getSubdivisions);
router.get('/subdivisions/:id/plan', requireScreen('maps', 'subdivisions'), mapController.getSubdivisionPlan);
router.put('/subdivisions/:id/plan-layout', requireScreen('maps'), requireRole('admin', 'engineer'), mapController.updateSubdivisionPlanLayout);
router.put('/subdivisions/:id/location', requireScreen('maps', 'subdivisions'), requireRole('admin', 'engineer'), mapController.updateSubdivisionLocation);
router.post('/maps', requireScreen('maps'), requireRole('admin', 'engineer'), mapController.create);
router.put('/maps/:id', requireScreen('maps'), requireRole('admin', 'engineer'), mapController.update);
router.post('/subdivisions', requireScreen('subdivisions'), requireRole('admin'), plantUpload, mapController.createSubdivision);
router.get('/concrete-pours', requireScreen('concrete'), concreteController.getAll);
router.post('/concrete-pours', requireScreen('concrete'), requireRole('admin', 'engineer'), concreteController.create);
router.patch('/concrete-pours/:id/status', requireScreen('concrete'), requireRole('admin', 'engineer'), concreteController.updateStatus);

module.exports = router;
